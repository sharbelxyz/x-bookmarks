def utc_now() -> dt.datetime:
    return dt.datetime.now(dt.timezone.utc)


def parse_iso(value: Any) -> Optional[dt.datetime]:
    if not value:
        return None
    text = str(value).strip()
    if text.endswith("Z"):
        text = text[:-1] + "+00:00"
    try:
        parsed = dt.datetime.fromisoformat(text)
    except ValueError:
        return None
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=dt.timezone.utc)
    return parsed


def next_cron_run(now: Optional[dt.datetime] = None) -> dt.datetime:
    """Next :17 / :47 boundary in the machine's local time zone."""
    now = now or dt.datetime.now().astimezone()
    candidates = []
    for offset_hours in (0, 1):
        base = (now + dt.timedelta(hours=offset_hours)).replace(second=0, microsecond=0)
        for minute in CRON_MINUTES:
            candidate = base.replace(minute=minute)
            if candidate > now:
                candidates.append(candidate)
    return min(candidates)


def build_health(data_dir: Path) -> Dict[str, Any]:
    status: Dict[str, Any] = {}
    status_error = ""
    try:
        with (data_dir / "status.json").open(encoding="utf-8") as handle:
            status = json.load(handle)
    except FileNotFoundError:
        status_error = "status.json is missing"
    except (OSError, json.JSONDecodeError) as exc:
        status_error = "status.json unreadable: {}".format(exc)

    now = utc_now()
    updated = parse_iso(status.get("updated_at"))
    age_seconds = None if updated is None else max(0, int((now - updated).total_seconds()))
    stale = age_seconds is None or age_seconds > STALE_AFTER_SECONDS

    dashboard = data_dir / "dashboard.html"
    dashboard_data = data_dir / "dashboard-data.json"

    def mtime_iso(path: Path) -> Optional[str]:
        try:
            return dt.datetime.fromtimestamp(path.stat().st_mtime, tz=dt.timezone.utc).isoformat(
                timespec="seconds"
            )
        except OSError:
            return None

    next_run = next_cron_run()
    payload = {
        "service": SERVICE_NAME,
        "ok": not status_error and dashboard.exists(),
        "now": now.isoformat(timespec="seconds"),
        "server_started_at": SERVER_STARTED_AT,
        "pid": os.getpid(),
        "status_updated_at": status.get("updated_at"),
        "status_error": status_error,
        "age_seconds": age_seconds,
        "stale": stale,
        "stale_after_seconds": STALE_AFTER_SECONDS,
        "gate_ready": bool(status.get("gate_ready")),
        "resources": status.get("resources"),
        "status_counts": status.get("status_counts"),
        "dashboard_modified_at": mtime_iso(dashboard),
        "dashboard_data_modified_at": mtime_iso(dashboard_data),
        "next_run_at": next_run.isoformat(timespec="seconds"),
        "cron_minutes": list(CRON_MINUTES),
    }
    # C4 additive block (A03): per-stage truth, run summary and backoff state.
    # Liveness (`ok` above) stays what it always was — this server reachable
    # and serving fresh files — while `stages` says whether the pipeline
    # actually succeeded. A composition failure must never take down the
    # health endpoint, and must be visible rather than silently absent.
    try:
        import run_health

        payload.update(run_health.compose_health_extension(data_dir, now))
    except Exception as exc:  # noqa: BLE001
        payload.update({
            "stages": {},
            "last_run_outcome": None,
            "last_run_at": None,
            "last_semantic_success_at": None,
            "auth_required": False,
            "backlog_age_seconds": None,
            "backoff": {"active": False, "until": None, "reason": None},
            "health_extension_error": str(exc)[:200],
        })
    return payload


class RadarHandler(BaseHTTPRequestHandler):
    server_version = "GroupRadar/1.0"
    sys_version = ""
    protocol_version = "HTTP/1.1"
    data_dir: Path = DATA_DIR
    # Connection-level socket timeout: bounds how long a stalled client can
    # retain a worker thread while reading the request line/headers. Large
    # enough that a polling dashboard tab reuses its keep-alive connection
    # without idle-timeout log noise. Body reads have their own tighter
    # deadline inside http_guards.read_json_object.
    timeout = 300

    # ----- helpers -----------------------------------------------------
    def _common_headers(self, content_type: str, length: int) -> None:
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(length))
        self.send_header("Cache-Control", "no-store, max-age=0")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "no-referrer")
        self.send_header("X-Frame-Options", "DENY")

    def _send_json(self, code: int, payload: Dict[str, Any]) -> None:
        body = json.dumps(payload, ensure_ascii=False, indent=2).encode("utf-8")
        self.send_response(code)
        self._common_headers("application/json; charset=utf-8", len(body))
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def _send_rejection(self, rejection: "http_guards.Rejection") -> None:
        """Answer a guard rejection and, when asked, close the connection so a
        wholly or partially unread body can never be parsed as a next request."""
        status, payload, close = rejection
        body = json.dumps(payload, ensure_ascii=False, indent=2).encode("utf-8")
        self.send_response(status)
        self._common_headers("application/json; charset=utf-8", len(body))
        if close:
            self.send_header("Connection", "close")
            self.close_connection = True
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def _server_port(self) -> int:
        try:
            return int(self.server.server_address[1])
        except (AttributeError, IndexError, TypeError, ValueError):
            return -1

    def _guard_host(self) -> bool:
        """DNS-rebinding guard, every verb: Host must be this loopback server."""
        rejection = http_guards.check_host(self.headers.get("Host"), self._server_port())
        if rejection:
            self._send_rejection(rejection)
            return False
        return True

    def _resolve(self, name: str) -> Optional[Path]:
        base = self.data_dir.resolve()
        candidate = (base / name).resolve()
        if candidate.parent != base or candidate.name != name:
            return None
        return candidate

    def _serve_file(self, name: str, content_type: str) -> None:
        path = self._resolve(name)
        if path is None or not path.is_file():
            self._send_json(HTTPStatus.NOT_FOUND, {"error": "not found", "path": self.path})
            return
        try:
            stat = path.stat()
            if stat.st_size > MAX_FILE_BYTES:
                self._send_json(HTTPStatus.INSUFFICIENT_STORAGE, {"error": "artifact too large"})
                return
            etag = '"{:x}-{:x}"'.format(stat.st_mtime_ns, stat.st_size)
            if self.headers.get("If-None-Match") == etag:
                self.send_response(HTTPStatus.NOT_MODIFIED)
                self.send_header("ETag", etag)
                self.send_header("Cache-Control", "no-store, max-age=0")
                self.end_headers()
                return
            body = path.read_bytes()
        except OSError as exc:
            self._send_json(HTTPStatus.SERVICE_UNAVAILABLE, {"error": "read failed: {}".format(exc)})
            return
        self.send_response(HTTPStatus.OK)
        self._common_headers(content_type, len(body))
        self.send_header("ETag", etag)
        self.send_header("Last-Modified", email.utils.formatdate(stat.st_mtime, usegmt=True))
        if content_type.startswith("text/html"):
            self.send_header("Content-Security-Policy", HTML_CSP)
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    # ----- verbs ---------------------------------------------------------
    def do_GET(self) -> None:  # noqa: N802 (http.server naming)
        if not self._guard_host():
            return
        route = self.path.split("?", 1)[0].split("#", 1)[0]
        if route == "/api/health":
            self._send_json(HTTPStatus.OK, build_health(self.data_dir))
            return
        if route == "/api/decisions":
            # C2-T-A10 read-back (lane 02 provider; registration is 07-owned).
            code, payload = read_decisions()
            self._send_json(code, payload)
            return
        if route in {"/api/run", "/api/verdict", "/api/outcome", "/api/negative-term"}:
            # POST-only endpoints: 405 is the honest answer, not 404.
            self._reject()
            return
        if route == "/favicon.ico":
            self.send_response(HTTPStatus.NO_CONTENT)
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", "0")
            self.end_headers()
            return
        target = ROUTES.get(route)
        if not target:
            self._send_json(HTTPStatus.NOT_FOUND, {"error": "not found", "path": route})
            return
        self._serve_file(*target)

    def do_HEAD(self) -> None:  # noqa: N802
        self.do_GET()

    def _reject(self) -> None:
        self.send_response(HTTPStatus.METHOD_NOT_ALLOWED)
        self.send_header("Allow", "GET, HEAD")
        self.send_header("Content-Length", "0")
        self.end_headers()

    def do_POST(self) -> None:  # noqa: N802
        if not self._guard_host():
            return
        route = self.path.split("?", 1)[0]
        if route in {"/api/verdict", "/api/outcome", "/api/negative-term"}:
            wanted = {"/api/verdict": "verdict", "/api/outcome": "outcome", "/api/negative-term": "negative-term"}[route]
            if self.headers.get(RUN_HEADER, "").strip().lower() != wanted:
                # Same 400 as always, but close: the body is unread.
                self._send_rejection(http_guards.Rejection(
                    HTTPStatus.BAD_REQUEST, {"error": "missing {} header".format(RUN_HEADER)}))
                return
            # Origin/Referer policy, content type, bounded read, JSON-object
            # shape and field hygiene — all before the handler can touch
            # stored state. See http_guards docstring for the documented
            # missing-Origin rule.
            body, rejection = http_guards.guard_mutation(self, self._server_port())
            if rejection:
                self._send_rejection(rejection)
                return
            handler = {
                "/api/verdict": record_verdict,
                "/api/outcome": record_outcome,
                "/api/negative-term": record_negative_term,
            }[route]
            code, payload = handler(body)
            self._send_json(code, payload)
            return
        if route != "/api/run":
            self._reject()
            return
        # A custom header forces a CORS preflight for any cross-origin page, and
        # the server never answers preflights, so only same-origin scripts get here.
        if self.headers.get(RUN_HEADER, "").strip().lower() != "run":
            self._send_json(HTTPStatus.BAD_REQUEST, {"error": "missing {} header".format(RUN_HEADER)})
            return
        # No body on this route, but the browser-mutation Origin policy applies.
        rejection = http_guards.check_origin(
            self.headers.get("Origin"), self.headers.get("Referer"),
            self.headers.get("Sec-Fetch-Site"), self._server_port())
        if rejection:
            self._send_rejection(rejection)
            return
        code, payload = trigger_run(self.data_dir)
        self._send_json(code, payload)

    do_PUT = do_DELETE = do_PATCH = do_OPTIONS = _reject

    # ----- logging -------------------------------------------------------
    def log_request(self, code: Any = "-", size: Any = "-") -> None:
        try:
            numeric = int(code)
        except (TypeError, ValueError):
            numeric = 0
        if numeric >= 400:
            super().log_request(code, size)

    def log_message(self, format: str, *args: Any) -> None:  # noqa: A002
        sys.stderr.write(
            "[radar-server {}] {}\n".format(
                dt.datetime.now().isoformat(timespec="seconds"), format % args
            )
        )
        sys.stderr.flush()


