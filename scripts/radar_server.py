def lookup_tool_type(key: str) -> str:
    """Canonical resource type for a tool key, from the scanner's projection.

    Returns "" when the index is missing, unreadable, or has no opinion; the
    caller then falls back to what the client offered. Never raises: typing is
    an enrichment here, and a broken index must not block a decision save.
    """
    import resource_typing

    try:
        raw = TOOL_INDEX_PATH.read_bytes()
    except OSError:
        return ""
    if len(raw) > MAX_FILE_BYTES:
        return ""
    try:
        payload = json.loads(raw.decode("utf-8"))
    except (ValueError, UnicodeDecodeError):
        return ""
    tools = payload.get("tools") if isinstance(payload, dict) else None
    if not isinstance(tools, list):
        return ""
    wanted = key.lower()
    for tool in tools:
        if isinstance(tool, dict) and str(tool.get("key", "")).lower() == wanted:
            candidate = str(tool.get("resource_type") or "")
            return candidate if candidate in resource_typing.RESOURCE_TYPES else ""
    return ""


def _parse_expected_revision(body: Dict[str, Any]) -> Tuple[Optional[int], Optional[Dict[str, Any]]]:
    """Optional optimistic-concurrency input; garbage gets a clear 400."""
    value = body.get("expected_revision")
    if value is None:
        return None, None
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        return None, {"error": "expected_revision must be a non-negative integer"}
    return value, None


# What a measured trial may additionally record (all optional; an unmeasured
# number stays absent — unknown is never fabricated into a result). Strings
# are length-capped; baseline/observed_result may be real numbers.
OUTCOME_TRIAL_FIELDS: Dict[str, int] = {
    "project": 120,
    "artifact": 200,
    "success_measure": 300,
    "baseline": 120,
    "observed_result": 300,
    "units": 40,
    "evidence": 600,
}


def _collect_trial_fields(body: Dict[str, Any]) -> Tuple[Dict[str, Any], Optional[Dict[str, Any]]]:
    """Validate the optional trial fields; only provided values are stored."""
    collected: Dict[str, Any] = {}
    for field, cap in OUTCOME_TRIAL_FIELDS.items():
        value = body.get(field)
        if value in (None, ""):
            continue
        if field in ("baseline", "observed_result") and isinstance(value, (int, float)) \
                and not isinstance(value, bool):
            collected[field] = value
            continue
        if not isinstance(value, str):
            return {}, {"error": "{} must be a string{}".format(
                field, " or a number" if field in ("baseline", "observed_result") else "")}
        collected[field] = value[:cap]
    trial_date = body.get("trial_date")
    if trial_date not in (None, ""):
        try:
            collected["trial_date"] = dt.date.fromisoformat(str(trial_date)).isoformat()
        except ValueError:
            return {}, {"error": "trial_date must be a YYYY-MM-DD date"}
    return collected, None


def record_verdict(body: Dict[str, Any], *, source: str = "dashboard",
                   source_event: str = "", actor: str = "") -> Tuple[int, Dict[str, Any]]:
    """Append or replace one hand-made verdict in config/verdicts.json.

    The whole point of the review queue is that the judgement stays the user's,
    so this is the shared validated write path for every ingress (dashboard
    HTTP, Telegram pull, agent sessions) and it writes exactly one reviewed
    entry per call. Persistence goes through ``decision_store``: inter-process
    locked, corruption fails closed with the bytes untouched, publication is
    atomic and durable, prior versions stay recoverable, and the response
    carries the authoritative stored record plus its on-disk revision.

    ``source``/``source_event``/``actor`` are server-side provenance chosen by
    the calling ingress, never by the request body: a browser cannot claim to
    be Telegram.
    """
    key = str(body.get("key") or "").strip().lstrip("/")
    verdict = str(body.get("verdict") or "").strip()
    if not key or "/" not in key:
        return HTTPStatus.BAD_REQUEST, {"error": "key must look like host/owner/name"}
    if verdict not in ALLOWED_VERDICTS and verdict != "clear":
        return HTTPStatus.BAD_REQUEST, {
            "error": "verdict must be one of {} or 'clear'".format(sorted(ALLOWED_VERDICTS))
        }
    expected_revision, revision_error = _parse_expected_revision(body)
    if revision_error:
        return HTTPStatus.BAD_REQUEST, revision_error

    # A verdict must fit what the thing actually is. "Must try" on an article
    # and "must read" on a CLI are category errors, and storing one silently
    # is how the two kinds get conflated in the first place. The type comes
    # from the client when offered, otherwise from the server's own tool
    # index, so the Telegram path is held to exactly the same rule as HTTP.
    import resource_typing

    resource_type = str(body.get("resource_type") or "").strip()
    type_source = "client" if resource_type else ""
    if resource_type and resource_type not in resource_typing.RESOURCE_TYPES:
        return HTTPStatus.BAD_REQUEST, {
            "error": "unknown resource_type '{}'; expected one of {}".format(
                resource_type, sorted(resource_typing.RESOURCE_TYPES)
            )
        }
    if not resource_type:
        resource_type = lookup_tool_type(key)
        type_source = "server_index" if resource_type else ""
    if verdict != "clear" and resource_type:
        if not resource_typing.verdict_fits_type(verdict, resource_type):
            allowed = sorted(resource_typing.VERDICT_FOR_TYPE.get(resource_type, set()))
            return HTTPStatus.CONFLICT, {
                "error": "'{}' does not fit a '{}' resource; allowed here: {}".format(
                    verdict, resource_type, allowed
                ),
                "hint": "{} means: {}".format(
                    resource_type, resource_typing.TYPE_VERBS.get(resource_type, "")
                ),
            }

    with _verdict_lock:
        try:
            with decision_store.locked_document(VERDICTS_PATH, "verdicts") as store:
                if expected_revision is not None and expected_revision != store.revision:
                    return HTTPStatus.CONFLICT, {
                        "error": "verdicts.json changed since this view was loaded",
                        "current_revision": store.revision,
                    }
                document = store.document
                entries = document["verdicts"]
                remaining = [e for e in entries if str(e.get("key", "")).lower() != key.lower()]
                removed = len(entries) - len(remaining)
                entry: Optional[Dict[str, Any]] = None
                if verdict == "clear":
                    document["verdicts"] = remaining
                    action = "cleared" if removed else "not present"
                else:
                    entry = {
                        "key": key,
                        "name": str(body.get("name") or key)[:200],
                        "verdict": verdict,
                        "why": str(body.get("why") or "")[:600],
                        "what": str(body.get("what") or "")[:400],
                        "first_step": str(body.get("first_step") or "")[:400],
                        "lane": str(body.get("lane") or "")[:120],
                        "reason_code": str(body.get("reason_code") or "")[:40],
                        "resource_type": resource_type,
                        "decided_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
                        "decided_by": source,
                    }
                    if type_source:
                        entry["resource_type_source"] = type_source
                    if source_event:
                        entry["source_event"] = str(source_event)[:80]
                    if actor:
                        entry["actor"] = str(actor)[:120]
                    for field in ("stars", "license", "last_push"):
                        if body.get(field) not in (None, ""):
                            entry[field] = body[field]
                    if verdict == "must_try":
                        ranks = [
                            int(e["rank"])
                            for e in remaining
                            if e.get("verdict") == "must_try" and isinstance(e.get("rank"), int)
                        ]
                        entry["rank"] = (max(ranks) + 1) if ranks else 1
                    remaining.append(entry)
                    document["verdicts"] = remaining
                    action = "replaced" if removed else "added"
                document["updated_at"] = dt.datetime.now(dt.timezone.utc).date().isoformat()
                revision = store.commit()
        except decision_store.StoreError as exc:
            return exc.status, exc.payload
    return HTTPStatus.OK, {
        "ok": True,
        "action": action,
        "key": key,
        "verdict": verdict,
        "total": len(document["verdicts"]),
        "revision": revision,
        "record": entry,
        "note": "Takes effect in the dashboard after the next export (within 30 minutes) or Scan now.",
    }


def record_outcome(body: Dict[str, Any], *, source: str = "dashboard") -> Tuple[int, Dict[str, Any]]:
    """Append or replace one outcome in config/outcomes.json.

    Structurally identical to record_verdict, deliberately: one validated,
    inter-process-locked, atomic write path per file, so neither can drift
    from the other. Kept in a separate file because clearing a verdict must
    not erase the fact that you tried the thing. ``source`` is server-side
    provenance chosen by the ingress, never taken from the body.
    """
    key = str(body.get("key") or "").strip().lstrip("/")
    state = str(body.get("state") or "").strip()
    if not key or "/" not in key:
        return HTTPStatus.BAD_REQUEST, {"error": "key must look like host/owner/name"}
    if state not in ALLOWED_OUTCOMES and state != "clear":
        return HTTPStatus.BAD_REQUEST, {
            "error": "state must be one of {} or 'clear'".format(sorted(ALLOWED_OUTCOMES))
        }
    expected_revision, revision_error = _parse_expected_revision(body)
    if revision_error:
        return HTTPStatus.BAD_REQUEST, revision_error
    trial_fields, trial_error = _collect_trial_fields(body)
    if trial_error:
        return HTTPStatus.BAD_REQUEST, trial_error
    with _outcome_lock:
        try:
            with decision_store.locked_document(OUTCOMES_PATH, "outcomes") as store:
                if expected_revision is not None and expected_revision != store.revision:
                    return HTTPStatus.CONFLICT, {
                        "error": "outcomes.json changed since this view was loaded",
                        "current_revision": store.revision,
                    }
                document = store.document
                entries = document["outcomes"]
                remaining = [e for e in entries if str(e.get("key", "")).lower() != key.lower()]
                removed = len(entries) - len(remaining)
                entry: Optional[Dict[str, Any]] = None
                if state == "clear":
                    document["outcomes"] = remaining
                    action = "cleared" if removed else "not present"
                else:
                    entry = {
                        "key": key,
                        "name": str(body.get("name") or key)[:200],
                        "state": state,
                        "note": str(body.get("note") or "")[:600],
                        "decided_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
                        "decided_by": source,
                    }
                    entry.update(trial_fields)
                    remaining.append(entry)
                    document["outcomes"] = remaining
                    action = "replaced" if removed else "added"
                document["updated_at"] = dt.datetime.now(dt.timezone.utc).date().isoformat()
                revision = store.commit()
        except decision_store.StoreError as exc:
            return exc.status, exc.payload
    return HTTPStatus.OK, {
        "ok": True,
        "action": action,
        "key": key,
        "state": state,
        "total": len(document["outcomes"]),
        "revision": revision,
        "record": entry,
    }


def record_negative_term(body: Dict[str, Any]) -> Tuple[int, Dict[str, Any]]:
    """Approve or withdraw one learned exclusion term.

    Writes to selection.negative_terms in the filter profile. Approving a rule is
    a bigger act than judging one tool, so the term is validated hard: it must be
    a single short token, and it may never shadow a term the profile already
    relies on to *accept* things.
    """
    term = str(body.get("term") or "").strip().lower()
    action = str(body.get("action") or "add").strip()
    if not term or len(term) < 3 or len(term) > 40 or any(c.isspace() for c in term):
        return HTTPStatus.BAD_REQUEST, {"error": "term must be a single token of 3-40 characters"}
    if action not in {"add", "remove"}:
        return HTTPStatus.BAD_REQUEST, {"error": "action must be 'add' or 'remove'"}
    with _profile_lock:
        try:
            with decision_store.locked_document(
                PROFILE_PATH, None, require_existing=True, bump_revision=False
            ) as store:
                profile = store.document
                selection = profile.get("selection")
                if not isinstance(selection, dict):
                    return HTTPStatus.INTERNAL_SERVER_ERROR, {"error": "profile has no selection block"}

                positive = {str(t).lower() for t in selection.get("ai_terms", [])}
                for area in (selection.get("project_areas") or {}).values():
                    positive.update(str(t).lower() for t in area.get("keywords", []))
                if action == "add" and term in positive:
                    return HTTPStatus.CONFLICT, {
                        "error": "'{}' is already a positive term; excluding on it would fight the rule beside it".format(term)
                    }

                current = [str(t) for t in selection.get("negative_terms", [])]
                if action == "add":
                    if term in (t.lower() for t in current):
                        return HTTPStatus.OK, {"ok": True, "action": "already present", "term": term, "total": len(current)}
                    current.append(term)
                else:
                    current = [t for t in current if t.lower() != term]
                selection["negative_terms"] = current
                store.commit()
        except decision_store.StoreError as exc:
            # Keep the long-standing external answer for a broken profile.
            if exc.status != HTTPStatus.SERVICE_UNAVAILABLE:
                return HTTPStatus.INTERNAL_SERVER_ERROR, {"error": "profile is unreadable"}
            return exc.status, exc.payload
    return HTTPStatus.OK, {
        "ok": True,
        "action": "added" if action == "add" else "removed",
        "term": term,
        "total": len(current),
        "note": "Applies to items the positive rules did not match, from the next scan on.",
    }


def read_decisions() -> Tuple[int, Dict[str, Any]]:
    """Fresh authoritative read-back of both authored decision files.

    Implementation for the C2-T-A10 additive route ``GET /api/decisions``
    (route registration itself belongs to the coordinator's dispatch). A
    successful save followed by this read must show the saved record without
    waiting for the next scanner export; a missing file is honestly an empty
    document, while a corrupt file is reported as an error instead of being
    passed off as empty history.
    """
    payload: Dict[str, Any] = {
        "ok": True,
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "verdicts_document": None,
        "outcomes_document": None,
        "revision": {"verdicts": None, "outcomes": None},
    }
    for name, path, container in (
        ("verdicts", VERDICTS_PATH, "verdicts"),
        ("outcomes", OUTCOMES_PATH, "outcomes"),
    ):
        document, revision, error = decision_store.read_document(path, container)
        if error:
            payload["ok"] = False
            payload.setdefault("errors", {})[name] = error
        else:
            payload["{}_document".format(name)] = document
            payload["revision"][name] = revision
    return HTTPStatus.OK, payload


def worker_lock_is_free(data_dir: Path) -> bool:
    """True when no monitor run currently holds data/group-monitor/worker.lock."""
    import fcntl

    lock_path = data_dir / "worker.lock"
    try:
        handle = lock_path.open("a+")
    except OSError:
        return True
    try:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        return False
    else:
        fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
        return True
    finally:
        handle.close()


def trigger_run(data_dir: Path, now: Optional[float] = None) -> Tuple[int, Dict[str, Any]]:
    """Start one bounded monitor run in the background (the same script cron runs)."""
    global _last_run_started_at
    import time

    now = time.monotonic() if now is None else now
    with _run_lock:
        elapsed = now - _last_run_started_at
        if _last_run_started_at and elapsed < RUN_COOLDOWN_SECONDS:
            return HTTPStatus.TOO_MANY_REQUESTS, {
                "started": False,
                "reason": "a scan was started {} s ago; wait {} s".format(
                    int(elapsed), int(RUN_COOLDOWN_SECONDS - elapsed)
                ),
            }
        if not LOOP_SCRIPT.exists():
            return HTTPStatus.SERVICE_UNAVAILABLE, {"started": False, "reason": "loop script is missing"}
        if not worker_lock_is_free(data_dir):
            return HTTPStatus.CONFLICT, {"started": False, "reason": "a scan is already running"}
        runtime_path = os.pathsep.join(
            path
            for path in ("/opt/homebrew/bin", "/usr/local/bin", "/usr/bin", "/bin", "/usr/sbin", "/sbin")
        )
        try:
            log_handle = (data_dir / RUN_LOG_NAME).open("a")
            process = subprocess.Popen(
                [sys.executable, str(LOOP_SCRIPT)],
                cwd=str(LOOP_SCRIPT.parent.parent),
                stdout=log_handle,
                stderr=subprocess.STDOUT,
                env={**os.environ, "PATH": runtime_path},
                start_new_session=True,
            )
            log_handle.close()
        except OSError as exc:
            return HTTPStatus.SERVICE_UNAVAILABLE, {"started": False, "reason": "could not start: {}".format(exc)}
        _last_run_started_at = now
        return HTTPStatus.ACCEPTED, {"started": True, "pid": process.pid, "cooldown_seconds": RUN_COOLDOWN_SECONDS}


def probe_existing(host: str, port: int) -> Optional[Dict[str, Any]]:
    try:
        with urllib.request.urlopen(
            "http://{}:{}/api/health".format(host, port), timeout=2
        ) as response:
            payload = json.loads(response.read().decode("utf-8"))
    except Exception:
        return None
    return payload if isinstance(payload, dict) else None


def architecture_refresh_loop(stop: threading.Event) -> None:
    """Keep documentation fresh without blocking requests or retaining old imports."""
    while not stop.is_set():
        try:
            result = subprocess.run(
                [sys.executable, str(ROOT / "scripts" / "generate_architecture.py"), "--refresh"],
                cwd=str(ROOT), capture_output=True, text=True, timeout=30, check=False,
            )
            if result.returncode:
                print("architecture refresh failed: " + (result.stderr or result.stdout)[-400:], file=sys.stderr, flush=True)
        except (OSError, subprocess.TimeoutExpired) as exc:
            print("architecture refresh failed: " + str(exc), file=sys.stderr, flush=True)
        if stop.wait(ARCHITECTURE_REFRESH_SECONDS):
            break


def serve(host: str, port: int, data_dir: Path) -> int:
    if host not in LOOPBACK_HOSTS:
        print("radar-server: refusing to bind non-loopback host {}".format(host), file=sys.stderr)
        return 2
    RadarHandler.data_dir = data_dir
    ThreadingHTTPServer.allow_reuse_address = True
    ThreadingHTTPServer.daemon_threads = True
    try:
        server = ThreadingHTTPServer((host, port), RadarHandler)
    except OSError as exc:
        existing = probe_existing(host, port)
        if existing and existing.get("service") == SERVICE_NAME:
            print(
                "radar-server: port {} already served by {} pid {}; nothing to do".format(
                    port, SERVICE_NAME, existing.get("pid")
                ),
                file=sys.stderr,
            )
            return 0
        print("radar-server: cannot bind {}:{} ({})".format(host, port, exc), file=sys.stderr)
        return 1

    def _stop(signum: int, _frame: Any) -> None:
        raise SystemExit(0)

    signal.signal(signal.SIGTERM, _stop)
    signal.signal(signal.SIGINT, _stop)
    print(
        "radar-server: serving {} at http://{}:{}/ (pid {})".format(data_dir, host, port, os.getpid()),
        file=sys.stderr,
    )
    sys.stderr.flush()
    architecture_stop = threading.Event()
    architecture_worker = threading.Thread(
        target=architecture_refresh_loop, args=(architecture_stop,), daemon=True,
        name="architecture-refresh",
    )
    architecture_worker.start()
    try:
        server.serve_forever(poll_interval=0.5)
    except SystemExit:
        pass
    finally:
        architecture_stop.set()
        architecture_worker.join(timeout=31)
        server.server_close()
    return 0


def main(argv: Optional[list] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", default=DEFAULT_HOST, help="loopback host only")
    parser.add_argument("--port", type=int, default=DEFAULT_PORT)
    parser.add_argument("--data-dir", type=Path, default=DATA_DIR)
    parser.add_argument(
        "--health",
        action="store_true",
        help="print the health document for the given host/port and exit",
    )
    args = parser.parse_args(argv)
    if args.health:
        payload = probe_existing(args.host, args.port)
        if not payload:
            print(json.dumps({"ok": False, "error": "no radar server responding"}))
            return 1
        print(json.dumps(payload, ensure_ascii=False, indent=2))
        return 0 if payload.get("ok") else 1
    return serve(args.host, args.port, args.data_dir)


if __name__ == "__main__":
    sys.exit(main())
