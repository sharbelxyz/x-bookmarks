#!/usr/bin/env python3
"""Read-only localhost server for the live Group Resource Radar dashboard.

Why this exists: the dashboard is a static file regenerated by the cron loop
twice an hour. Opening it via ``file://`` gives a frozen snapshot, because
browsers refuse ``fetch`` on local files. Serving the same directory over
``http://127.0.0.1`` lets the page poll ``status.json`` and re-render itself
in place whenever the monitor produces new data.

Safety properties (deliberate, do not loosen without reason):

* binds loopback only; refuses any non-loopback host
* GET and HEAD only; every other method is 405
* serves an explicit whitelist of files from ``data/group-monitor``; nothing
  else is reachable (no directory listing, no SQLite, no credentials)
* symlink-escape check on every resolved path
* ``Cache-Control: no-store`` so the browser never shows a stale copy
* logs only errors, so a tab polling for weeks does not grow the log
* if the port is already held by *this* service, exits 0 so launchd stops
  retrying; if held by something else, exits 1 with a clear message
"""

